import json
import requests
from django.conf import settings

# Configuration variables
OLLAMA_HOST = getattr(settings, 'OLLAMA_HOST', 'http://localhost:11434')
DEFAULT_OLLAMA_MODEL = getattr(settings, 'OLLAMA_MODEL', 'qwen2.5:0.5b')
OLLAMA_TIMEOUT = getattr(settings, 'OLLAMA_TIMEOUT', 45) # 45 seconds timeout for generation

class OllamaConnectionError(Exception):
    """Exception raised when unable to connect to the Ollama server."""
    pass

class OllamaTimeoutError(Exception):
    """Exception raised when the Ollama request times out."""
    pass

class OllamaResponseError(Exception):
    """Exception raised when Ollama returns an error or invalid JSON."""
    pass


def send_chat_to_ollama(prompt, conversation_history=None, model=None, temperature=0.7, max_tokens=2048):
    """
    Sends a list of messages (conversation history + new prompt) to the local Ollama API.
    
    Args:
        prompt (str): The latest message from the user.
        conversation_history (list): List of dicts representing past messages, e.g.
            [{'role': 'user', 'content': '...'}, {'role': 'assistant', 'content': '...'}]
        model (str): The Ollama model name to use. Falls back to DEFAULT_OLLAMA_MODEL.
        temperature (float): Controls randomness (0.0 to 1.0).
        max_tokens (int): Maximum tokens to generate.
        
    Returns:
        str: The text content generated by Ollama.
    """
    if not model or model in ['UMI-Standard (v1.0)', 'UMI-Pro (v1.5)', 'UMI-Ultra (v2.0)']:
        model = DEFAULT_OLLAMA_MODEL
        
    url = f"{OLLAMA_HOST}/api/chat"
    
    # Format the message history
    messages = []
    
    # Inject UMI System Prompt to set the model persona
    system_prompt = (
        "You are UMI, a helpful, intelligent, and premium AI chat assistant. "
        "You always identify yourself as UMI. You are friendly, concise, and professional. "
        "Do not refer to yourself as Qwen or Alibaba Cloud. You are UMI."
    )
    messages.append({
        'role': 'system',
        'content': system_prompt
    })
    
    if conversation_history:
        for msg in conversation_history:
            messages.append({
                'role': msg.get('role'),
                'content': msg.get('content')
            })
            
    # For small models, prepend a direct reminder in the user message so it is followed
    prompt_with_reminder = (
        f"[System Instruction: You are UMI. You must refer to yourself as UMI. "
        f"Do not mention Qwen or Alibaba. Respond as UMI.]\n\n"
        f"User: {prompt}"
    )
    
    # Append the new user prompt
    messages.append({
        'role': 'user',
        'content': prompt_with_reminder
    })
    
    payload = {
        'model': model,
        'messages': messages,
        'stream': False,
        'options': {
            'temperature': temperature,
            'num_predict': max_tokens
        }
    }
    
    try:
        response = requests.post(url, json=payload, timeout=OLLAMA_TIMEOUT)
    except requests.exceptions.Timeout:
        raise OllamaTimeoutError("Request to Ollama timed out. The model might be loading or the prompt was too complex.")
    except requests.exceptions.ConnectionError:
        raise OllamaConnectionError("Ollama is not running. Please start Ollama using 'ollama serve'.")
    except requests.exceptions.RequestException as e:
        raise OllamaConnectionError(f"HTTP Connection to Ollama failed: {e}")
        
    if response.status_code != 200:
        raise OllamaResponseError(f"Ollama server returned an error (HTTP {response.status_code}): {response.text}")
        
    try:
        response_json = response.json()
    except json.JSONDecodeError:
        raise OllamaResponseError("Invalid JSON response received from the Ollama server.")
        
    if 'message' not in response_json or 'content' not in response_json['message']:
        raise OllamaResponseError("Unexpected response structure from Ollama API.")
        
    reply = response_json['message']['content']
    
    # Post-processing replacement filter to safeguard UMI identity
    reply = reply.replace("Qwen", "UMI")
    reply = reply.replace("Alibaba Cloud", "UMI Team")
    reply = reply.replace("Alibaba", "UMI Team")
    
    return reply
